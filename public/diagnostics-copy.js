export const DIAGNOSTICS_MESSAGES = { en, 'zh-Hant': zhHant };

function format(template, vars) {
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, key) => (
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : match
  ));
}

/** A `t` over one locale's diagnostics copy, falling back to English. */
export function diagnosticsTranslator(locale = 'en') {
  const table = DIAGNOSTICS_MESSAGES[locale] ?? en;
  return (key, vars = {}) => format(table[key] ?? en[key] ?? key, vars);
}

/** `{base}.one` for exactly one, `{base}.other` otherwise; `{count}` is filled in. */
export function plural(t, base, count) {
  return t(`${base}.${count === 1 ? 'one' : 'other'}`, { count });
}
